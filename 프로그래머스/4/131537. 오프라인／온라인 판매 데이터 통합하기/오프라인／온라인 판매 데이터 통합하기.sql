SELECT * FROM
(SELECT SALES_DATE AS SALES_DATE, PRODUCT_ID, USER_ID, SALES_AMOUNT
 FROM ONLINE_SALE ONL
 UNION
 SELECT SALES_DATE AS SALES_DATE, PRODUCT_ID, NULL, SALES_AMOUNT
 FROM OFFLINE_SALE OFL) A
 WHERE SALES_DATE >= STR_TO_DATE('20220301','%Y%m%d')
 AND SALES_DATE < STR_TO_DATE('20220401','%Y%m%d')
 ORDER BY SALES_DATE, PRODUCT_ID, USER_ID